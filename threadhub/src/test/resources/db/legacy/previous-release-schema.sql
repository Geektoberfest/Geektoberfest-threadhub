-- Previous-release schema, as Hibernate created it while spring.jpa.hibernate.ddl-auto=update was
-- still in use. This is a snapshot of a database that exists "in the wild" before Flyway took over,
-- so it deliberately keeps everything about that state:
--
--   * Hibernate's generated constraint names (`uk...`/`fk...` hashes) instead of readable names,
--   * the inline `community_members_role_check` created for the @Enumerated(EnumType.STRING) role,
--   * identity columns with their default `<table>_id_seq` sequences,
--   * no `flyway_schema_history` table.
--
-- It is intentionally unqualified (no `public.` prefixes) so it can be loaded into a throwaway schema.
-- Do not add migrations here and do not "fix" it to look like V1: the point is that a released
-- database looks like this, and the Flyway migrations must upgrade it to exactly the schema a fresh
-- install gets. See LegacySchemaUpgradeTest.

